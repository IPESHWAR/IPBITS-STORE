export const LANG_STORAGE_KEY = 'ipbits-lang';

/** Kurdistan / Duhok market display rate (IQD per 1 USD). */
export const IQD_PER_USD = 1560;

/** Round converted IQD to this step for clean local denominations. */
export const IQD_ROUND_TO = 500;

const LANG_ALIASES = {
  krd: 'ku',
  ku: 'ku',
  ckb: 'ku',
  kurdish: 'ku',
  ar: 'ar',
  arabic: 'ar',
  en: 'en',
  english: 'en',
};

export function normalizeLang(lang) {
  return LANG_ALIASES[String(lang || '').trim().toLowerCase()] || 'ku';
}

export function isRtl(lang) {
  return normalizeLang(lang) !== 'en';
}

export function usesUsd(lang) {
  return normalizeLang(lang) === 'en';
}

/** Convert USD → IQD using the store rate, rounded to nearest IQD_ROUND_TO. */
export function usdToIqd(usd) {
  const n = Number(usd);
  if (!Number.isFinite(n) || n <= 0) return 0;
  return Math.round((n * IQD_PER_USD) / IQD_ROUND_TO) * IQD_ROUND_TO;
}

export function toUsdAmount(iqd, usd) {
  const usdNum = Number(usd);
  if (Number.isFinite(usdNum) && usdNum > 0) return usdNum;
  const iqdNum = Number(iqd || 0);
  if (!Number.isFinite(iqdNum) || iqdNum <= 0) return 0;
  return Math.round((iqdNum / IQD_PER_USD) * 100) / 100;
}

/** Prefer USD → IQD when USD is set so rate changes apply store-wide. */
export function toIqdAmount(iqd, usd) {
  const usdNum = Number(usd);
  if (Number.isFinite(usdNum) && usdNum > 0) return usdToIqd(usdNum);
  const iqdNum = Number(iqd);
  if (Number.isFinite(iqdNum) && iqdNum > 0) return iqdNum;
  return 0;
}

export function moneyFrom(item) {
  if (item == null || typeof item !== 'object') {
    return { iqd: Number(item || 0), usd: 0 };
  }
  let iqd = Number(item.price_iqd ?? item.priceIQD ?? item.iqd ?? 0);
  let usd = Number(item.price_usd ?? item.priceUSD ?? item.usd ?? 0);

  // Product cards sometimes pass the product object; prices may live only on plans.
  if (
    (!Number.isFinite(usd) || usd <= 0) &&
    (!Number.isFinite(iqd) || iqd <= 0) &&
    Array.isArray(item.plans) &&
    item.plans.length
  ) {
    const plan = item.plans.reduce((lowest, next) => {
      const nextUsd = Number(next?.price_usd ?? next?.priceUSD ?? Infinity);
      const lowestUsd = Number(lowest?.price_usd ?? lowest?.priceUSD ?? Infinity);
      const nextIqd = Number(next?.price_iqd ?? next?.priceIQD ?? Infinity);
      const lowestIqd = Number(lowest?.price_iqd ?? lowest?.priceIQD ?? Infinity);
      if (Number.isFinite(nextUsd) && Number.isFinite(lowestUsd)) {
        return nextUsd < lowestUsd ? next : lowest;
      }
      return nextIqd < lowestIqd ? next : lowest;
    }, item.plans[0]);
    iqd = Number(plan?.price_iqd ?? plan?.priceIQD ?? 0);
    usd = Number(plan?.price_usd ?? plan?.priceUSD ?? 0);
  }

  if (Number.isFinite(usd) && usd > 0) {
    iqd = usdToIqd(usd);
  } else if ((!Number.isFinite(usd) || usd <= 0) && Number.isFinite(iqd) && iqd > 0) {
    usd = toUsdAmount(iqd, 0);
  }

  return {
    iqd: Number.isFinite(iqd) ? iqd : 0,
    usd: Number.isFinite(usd) ? usd : 0,
  };
}

export function formatPrice(lang, iqd, usd) {
  if (usesUsd(lang)) return `$${toUsdAmount(iqd, usd).toFixed(2)}`;
  const amount = toIqdAmount(iqd, usd);
  const formatted = amount.toLocaleString('en-US');
  return normalizeLang(lang) === 'ar' || normalizeLang(lang) === 'ku'
    ? `${formatted} د.ع`
    : `${formatted} IQD`;
}

export function formatTotal(lang, totalIQD, totalUSD) {
  return formatPrice(lang, totalIQD, totalUSD);
}

export function formatMoney(lang, item) {
  const { iqd, usd } = moneyFrom(item);
  return formatPrice(lang, iqd, usd);
}

const ARABIC_INDIC_DIGITS = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

export function toLocalizedNumber(value, lang) {
  const rounded = Math.round(value).toLocaleString('en-US');
  if (lang === 'en') return rounded;
  return rounded.replace(/[0-9]/g, (d) => ARABIC_INDIC_DIGITS[Number(d)]);
}

